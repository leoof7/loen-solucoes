-- ============================================================
-- LOEN SOLUÇÕES — Gera o docs/migracoes/00-estrutura-completa.sql
--
-- Só LÊ o banco. Rode em PRODUÇÃO; o resultado é uma linha com o SQL
-- que recria a estrutura inteira (sem dados) num projeto novo.
-- ============================================================

with
tabs as (
  select c.oid, c.relname, format('public.%I', c.relname) as nome, c.relrowsecurity, c.relforcerowsecurity
  from pg_class c where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
),
colunas as (
  select t.oid, string_agg(
    format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
    || case when a.attidentity = 'd' then ' generated by default as identity'
            when a.attidentity = 'a' then ' generated always as identity' else '' end
    || coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), '')
    || case when a.attnotnull then ' not null' else '' end,
    E',\n' order by a.attnum) as cols
  from tabs t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  group by t.oid
),
restr as (
  select t.oid, string_agg(format('  constraint %I %s', co.conname, pg_get_constraintdef(co.oid)), E',\n' order by co.contype, co.conname) as r
  from tabs t join pg_constraint co on co.conrelid = t.oid and co.contype in ('p','u','c','x')
  group by t.oid
),
sec as (
  select string_agg(format('create sequence if not exists public.%I;', s.relname), E'\n') as x
  from pg_class s where s.relnamespace = 'public'::regnamespace and s.relkind = 'S'
),
tabelas as (
  select string_agg(format(E'create table %s (\n%s%s\n);', t.nome, c.cols, coalesce(E',\n' || r.r, '')), E'\n\n' order by t.relname) as x
  from tabs t join colunas c using (oid) left join restr r using (oid)
),
donos_seq as (
  select string_agg(format('alter sequence public.%I owned by public.%I.%I;', s.relname, t.relname, a.attname), E'\n') as x
  from pg_class s
  join pg_depend dp on dp.objid = s.oid and dp.deptype = 'a'
  join pg_class t on t.oid = dp.refobjid
  join pg_attribute a on a.attrelid = t.oid and a.attnum = dp.refobjsubid
  where s.relnamespace = 'public'::regnamespace and s.relkind = 'S'
),
fks as (
  select string_agg(format('alter table %s add constraint %I %s;', t.nome, co.conname, pg_get_constraintdef(co.oid)), E'\n' order by t.relname, co.conname) as x
  from tabs t join pg_constraint co on co.conrelid = t.oid and co.contype = 'f'
),
indices as (
  select string_agg(pg_get_indexdef(i.indexrelid) || ';', E'\n' order by 1) as x
  from pg_index i join tabs t on t.oid = i.indrelid
  where not exists (select 1 from pg_constraint co where co.conindid = i.indexrelid)
),
comentarios as (
  select string_agg(format('comment on table %s is %L;', t.nome, obj_description(t.oid, 'pg_class')), E'\n') as x
  from tabs t where obj_description(t.oid, 'pg_class') is not null
),
funcoes as (
  select string_agg(pg_get_functiondef(p.oid) || ';', E'\n\n' order by p.pronamespace::regnamespace::text, p.proname) as x
  from pg_proc p where p.pronamespace in ('public'::regnamespace, 'private'::regnamespace)
),
gatilhos as (
  select string_agg(pg_get_triggerdef(tg.oid) || ';', E'\n' order by tg.tgname) as x
  from pg_trigger tg join tabs t on t.oid = tg.tgrelid where not tg.tgisinternal
),
rls as (
  select string_agg(format('alter table %s enable row level security;', nome)
    || case when relforcerowsecurity then format(E'\nalter table %s force row level security;', nome) else '' end, E'\n' order by relname) as x
  from tabs where relrowsecurity
),
politicas as (
  select string_agg(format('create policy %I on %I.%I as %s for %s to %s%s%s;',
      policyname, schemaname, tablename, lower(permissive), lower(cmd),
      array_to_string(roles, ', '),
      coalesce(' using (' || qual || ')', ''),
      coalesce(' with check (' || with_check || ')', '')), E'\n' order by schemaname, tablename, policyname) as x
  from pg_policies where schemaname in ('public', 'storage')
),
acl_tab2 as (
  select string_agg(linha, E'\n' order by o, k, linha) as x from (
    select format('revoke all on table %s from anon, authenticated;', t.nome) as linha, t.relname as o, 0 as k from tabs t
    union all
    select format('grant %s on table %s to %I;', string_agg(e.privilege_type, ', ' order by e.privilege_type), t.nome, g.rolname), t.relname, 1
    from tabs t
    join pg_class c on c.oid = t.oid
    cross join lateral aclexplode(c.relacl) e
    join pg_roles g on g.oid = e.grantee
    where g.rolname in ('anon', 'authenticated')
    group by t.nome, g.rolname, t.relname
  ) s
),
acl_fn as (
  select string_agg(linha, E'\n' order by o, k, linha) as x from (
    select format('revoke all on function %s from public, anon, authenticated;', p.oid::regprocedure) as linha, p.proname::text as o, 0 as k
    from pg_proc p where p.pronamespace in ('public'::regnamespace, 'private'::regnamespace) and p.proacl is not null
    union all
    select format('grant execute on function %s to %s;', p.oid::regprocedure, case when e.grantee = 0 then 'public' else quote_ident(g.rolname) end), p.proname, 1
    from pg_proc p cross join lateral aclexplode(p.proacl) e
    left join pg_roles g on g.oid = e.grantee
    where p.pronamespace in ('public'::regnamespace, 'private'::regnamespace) and p.proacl is not null
      and (e.grantee = 0 or g.rolname in ('anon', 'authenticated', 'service_role'))
  ) s
),
baldes as (
  select string_agg(format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %L) on conflict (id) do nothing;',
    id, name, case when public then 'true' else 'false' end, coalesce(file_size_limit::text, 'null'), allowed_mime_types), E'\n') as x
  from storage.buckets
)
select concat_ws(E'\n\n',
  '-- ============================================================',
  '-- LOEN SOLUÇÕES — Estrutura completa do banco (gerada da produção em ' || to_char(now() at time zone 'America/Sao_Paulo', 'DD/MM/YYYY HH24:MI') || ')',
  '-- Cria um banco igual ao de produção, SEM dados. Rodar num projeto novo.',
  '-- ============================================================',
  'set check_function_bodies = off;',
  'create schema if not exists private;' || E'\nrevoke all on schema private from public, anon;\ngrant usage on schema private to authenticated;',
  '-- Sequências', (select x from sec),
  '-- Tabelas', (select x from tabelas),
  '-- Donos das sequências', (select x from donos_seq),
  '-- Ligações entre tabelas', (select x from fks),
  '-- Índices', (select x from indices),
  '-- Comentários', (select x from comentarios),
  '-- Funções', (select x from funcoes),
  '-- Gatilhos', (select x from gatilhos),
  '-- Travas de segurança (RLS)', (select x from rls),
  '-- Regras de acesso', (select x from politicas),
  '-- Permissões das tabelas', (select x from acl_tab2),
  '-- Permissões das funções', (select x from acl_fn),
  '-- Pastas de arquivos', (select x from baldes),
  E'-- Liga a trava de segurança sozinha em toda tabela nova\ndo $e$ begin\n  if not exists (select 1 from pg_event_trigger where evtname = ''ensure_rls'') then\n    create event trigger ensure_rls on ddl_command_end execute function public.rls_auto_enable();\n  end if;\nend $e$;'
) as estrutura;
